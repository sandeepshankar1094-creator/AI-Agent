from langchain_core.runnables import Runnable

from deployment_agent.agent.models import AgentState
from deployment_agent.integrations.github_api import GitHubClient
from deployment_agent.tools.helm_values import (
    extract_natural_language_overrides,
    generate_helm_repository_files,
    helm_merge_warnings,
)
from deployment_agent.tools.request_intent import requests_helm_parameter_update


_HELM_REPOSITORY_OWNER = "sandeepshankar1094-creator"
_HELM_REPOSITORY_NAME = "Helm-Charts"
_HELM_BRANCH = "agent-automation"


def add_helm_repository_files(
    state: AgentState,
    values_model: Runnable | None = None,
    client: GitHubClient | None = None,
) -> AgentState:
    requirement = state.get("requirement", "")
    natural_language_overrides = None
    if values_model and requests_helm_parameter_update(requirement):
        natural_language_overrides = extract_natural_language_overrides(
            requirement, values_model
        )

    existing_values_content = None
    default_values_content = None
    if client:
        helm_default_branch, _ = client.inspect_repository(
            _HELM_REPOSITORY_OWNER, _HELM_REPOSITORY_NAME
        )
        repo_name = state["repo"].lower()
        prefix = repo_name.split("-", 1)[0]
        existing_values_path = f"Application/{prefix}/{repo_name}/values.yaml"
        existing_values_content = client.get_file(
            _HELM_REPOSITORY_OWNER,
            _HELM_REPOSITORY_NAME,
            existing_values_path,
            _HELM_BRANCH,
        )
        default_values_content = client.get_file(
            _HELM_REPOSITORY_OWNER,
            _HELM_REPOSITORY_NAME,
            existing_values_path,
            helm_default_branch,
        )

    generated = generate_helm_repository_files(
        state["repo"],
        requirement,
        natural_language_overrides,
        existing_values_content,
        default_values_content,
    )
    return {
        "external_generated_files": generated,
        "helm_merge_warnings": helm_merge_warnings(
            default_values_content, existing_values_content
        ),
    }


def create_helm_repository_pull_request(
    state: AgentState, client: GitHubClient
) -> str:
    branch, _ = client.inspect_repository(
        _HELM_REPOSITORY_OWNER, _HELM_REPOSITORY_NAME
    )
    return client.create_pull_request(
        _HELM_REPOSITORY_OWNER,
        _HELM_REPOSITORY_NAME,
        branch,
        _HELM_BRANCH,
        state["external_generated_files"],
        f"Add Helm configuration for {state['repo']}",
        (
            "Generated by Deployment Agent.\n\n"
            f"- Adds ConfigMap and values configuration for `{state['repo']}`.\n"
            "- Source files were rendered from the configured Helm templates."
        ),
    )
